// Segmentos de URL traducidos. El español va en la raíz; el resto con prefijo de idioma.
const SEG = {
  es: { plan: 'plan', topics: 'temas', places: 'lugares', calendar: 'calendario' },
  en: { plan: 'plan', topics: 'topics', places: 'places', calendar: 'calendar' },
  fr: { plan: 'plan', topics: 'themes', places: 'lieux', calendar: 'calendrier' },
  de: { plan: 'plan', topics: 'themen', places: 'orte', calendar: 'kalender' },
  it: { plan: 'piano', topics: 'temi', places: 'luoghi', calendar: 'calendario' },
  pt: { plan: 'plano', topics: 'temas', places: 'locais', calendar: 'calendario' },
};
const pre = (l) => (l === DEFAULT_LANG ? '/' : `/${l}/`);
const topicSlug = (l, tp) => (l === DEFAULT_LANG ? tp.id : tp.slugs[l]);

export const url = {
  home: (l) => pre(l),
  plan: (l, slug) => `${pre(l)}${SEG[l].plan}/${slug}/`,
  topics: (l) => `${pre(l)}${SEG[l].topics}/`,
  topic: (l, tp) => `${pre(l)}${SEG[l].topics}/${topicSlug(l, tp)}/`,
  places: (l) => `${pre(l)}${SEG[l].places}/`,
  ccaa: (l, c) => `${pre(l)}${SEG[l].places}/${c}/`,
  province: (l, c, p) => `${pre(l)}${SEG[l].places}/${c}/${p}/`,
  calendar: (l) => `${pre(l)}${SEG[l].calendar}/`,
  month: (l, m) => `${pre(l)}${SEG[l].calendar}/${MONTHS[l][m - 1]}/`,
};

/**
 * Una "ruta" es un objeto neutro al idioma: { type: 'home' | 'plan' | 'topics' | 'topic' | 'places'
 * | 'ccaa' | 'province' | 'calendar' | 'month', ... }. Sirve para construir la URL en cualquier
 * idioma y, por tanto, los hreflang y el selector de idioma.
 */
export function routeUrl(l, r) {
  switch (r.type) {
    case 'home': return url.home(l);
    case 'plan': return url.plan(l, r.slug);
    case 'topics': return url.topics(l);
    case 'topic': return url.topic(l, r.tp);
    case 'places': return url.places(l);
    case 'ccaa': return url.ccaa(l, r.c);
    case 'province': return url.province(l, r.c, r.s);
    case 'calendar': return url.calendar(l);
    case 'month': return url.month(l, r.m);
    default: throw new Error(`Ruta desconocida: ${r.type}`);
  }
}

